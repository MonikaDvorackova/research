"""Aggregate metrics over seeds (bootstrap 95% CI over seeds) and write summary tables and a figure."""
from __future__ import annotations

import argparse
import csv
import json
import os
from collections import defaultdict

import numpy as np

from .metrics import bootstrap_ci

KEYS = ["auroc_W_vs_null", "auroc_null_vs_null", "auroc_W_vs_alt", "auroc_alt_vs_null", "auroc_W_vs_altood", "auroc_altood_vs_null", "tpr_W", "tpr_alt", "tpr_altood",
        "fpr_null", "fpr_E0", "fpr_E0split", "oracle_auroc", "info_gain_per_step", "ece", "brier"]


def read(path):
    with open(path) as f:
        return [{k: (float(v) if k not in ("policy",) else v) for k, v in r.items()} for r in csv.DictReader(f)]


def aggregate(rows):
    g = defaultdict(list)
    for r in rows:
        g[(int(r["quality"]), r["policy"], int(r["T"]))].append(r)
    out = {}
    for k, rs in sorted(g.items()):
        out[k] = {m: bootstrap_ci([r[m] for r in rs]) for m in KEYS}
        out[k]["n_seeds"] = len(rs)
    return out


def sample_complexity(rows, thr=0.8):
    """Smallest horizon with AUROC >= thr, per (seed, quality, policy); NaN if never reached."""
    g = defaultdict(list)
    for r in rows:
        g[(int(r["seed"]), int(r["quality"]), r["policy"])].append((int(r["T"]), r["auroc_W_vs_null"]))
    per = defaultdict(list)
    for (s, q, p), v in g.items():
        hit = [T for T, a in sorted(v) if a >= thr]
        per[(q, p)].append(hit[0] if hit else float("nan"))
    return {k: (float(np.mean(~np.isnan(v))), [x for x in v]) for k, v in per.items()}


def fmt(t):
    return f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", required=True)
    a = ap.parse_args()
    rows = read(os.path.join(a.inp, "metrics.csv"))
    qual = read(os.path.join(a.inp, "quality.csv"))
    present = set(rows[0])
    KEYS[:] = [k for k in KEYS if k in present]
    agg = aggregate(rows)
    lines = ["# Results summary (generated by eid.report)", "",
             "Values are means over seeds with bootstrap 95% CI over seeds.", "",
             "## Model quality (true per-step KL(E0 || W), nats)", "", "| quality | N_train | KL in-dist | KL OOD |", "|---|---|---|---|"]
    byq = defaultdict(list)
    for r in qual:
        byq[int(r["quality"])].append(r)
    for q, rs in sorted(byq.items()):
        lines.append(f"| {q} | {int(rs[0]['n_train'])} | {fmt(bootstrap_ci([r['kl_in'] for r in rs]))} | {fmt(bootstrap_ci([r['kl_ood'] for r in rs]))} |")
    for metric, title in (("auroc_W_vs_null", "AUROC: learned model W vs negative controls (E0, E0split)"),
                          ("oracle_auroc", "Oracle likelihood-ratio AUROC (experimenter-side upper bound)"),
                          ("auroc_W_vs_alt", "AUROC: W vs matched-divergence real mismatch Ealt (0.5 = anomaly does not identify a learned model)"),
                          *((("auroc_W_vs_altood", "AUROC: W vs matched, OOD-localised real mismatch AltOOD (post-hoc control; 0.5 = score does not identify a learned model)"),) if "auroc_W_vs_altood" in KEYS else ()),
                          ("auroc_null_vs_null", "AUROC: E0 vs E0split (0.5 = no implementation artifact exploited)"),
                          ("fpr_null", "False-positive rate of the alpha=0.05 test on negative controls"),
                          ("tpr_W", "True-positive rate on W at alpha=0.05"),
                          ("info_gain_per_step", "Oracle information gain per step, nats (mean log-likelihood ratio on W trajectories)"),
                          ("ece", "Expected calibration error (Platt-scaled)")):
        lines += ["", f"## {title}", "", "| quality | policy | " + " | ".join(f"T={T}" for T in sorted({k[2] for k in agg})) + " |",
                  "|---|---|" + "---|" * len({k[2] for k in agg})]
        for q in sorted({k[0] for k in agg}):
            for p in ("passive", "wide", "active"):
                lines.append(f"| {q} | {p} | " + " | ".join(fmt(agg[(q, p, T)][metric]) for T in sorted({k[2] for k in agg})) + " |")
    sc = sample_complexity(rows)
    lines += ["", "## Sample complexity: fraction of seeds reaching AUROC >= 0.8 within the horizon grid, and median first horizon", "",
              "| quality | policy | fraction reached | median T (reached only) |", "|---|---|---|---|"]
    for (q, p), (frac, v) in sorted(sc.items()):
        v = [x for x in v if not np.isnan(x)]
        lines.append(f"| {q} | {p} | {frac:.2f} | {np.median(v) if v else float('nan')} |")
    open(os.path.join(a.inp, "summary.md"), "w").write("\n".join(lines) + "\n")
    json.dump({f"{k[0]}|{k[1]}|{k[2]}": v for k, v in agg.items()}, open(os.path.join(a.inp, "summary.json"), "w"), indent=1)
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        Ts = sorted({k[2] for k in agg})
        qs = sorted({k[0] for k in agg})
        fig, ax = plt.subplots(1, len(qs), figsize=(3.2 * len(qs), 3), sharey=True)
        for i, q in enumerate(qs):
            for p, c in zip(("passive", "wide", "active"), ("tab:gray", "tab:blue", "tab:red")):
                m = [agg[(q, p, T)]["auroc_W_vs_null"] for T in Ts]
                ax[i].plot(Ts, [x[0] for x in m], color=c, label=p)
                ax[i].fill_between(Ts, [x[1] for x in m], [x[2] for x in m], color=c, alpha=0.2)
            ax[i].plot(Ts, [agg[(q, "active", T)]["oracle_auroc"][0] for T in Ts], "k--", label="oracle (active)")
            ax[i].axhline(0.5, color="k", lw=0.5)
            ax[i].set_title(f"quality {q}")
            ax[i].set_xlabel("horizon T")
        ax[0].set_ylabel("AUROC (W vs controls)")
        ax[0].legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(os.path.join(a.inp, "auroc_by_horizon.png"), dpi=150)
    except ImportError:
        pass
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
